#!/usr/bin/env python3
"""Exercise the borrowed HDCP2 manager binding; qualify its native consumer."""
from pathlib import Path
import re, subprocess, tempfile, sys

r = Path(__file__).resolve().parents[1]
s = (r / 'WhateverXe/kern_xe.cpp').read_text()
install = s[s.index('bool XE::processFramebufferDonorRuntime('):s.index('bool XE::processKextFull(')]
wrapper = re.search(r'bool XE::wrapTGLHDCP2Init\(.*?\n\}', s, re.S).group()
assert s.count('processFramebufferDonorRuntime(patcher,index,address,size);') == 1
assert s.count('wrapTGLMEIWrite,orgTGLMEIWrite') == 1
assert 'wrapTGLMEIWrite, orgTGLMEIWrite' not in s
assert 'tglPanelPowerPropertyReady && meiReady && ddiRequestReady' in install
assert 'XELPDonor::ddiReleaseSite' in install and 'WEXDonorDDIRequestReady' in install
if len(sys.argv) > 1:
    b = Path(sys.argv[1]).read_bytes()
    for name, offset in [('init',0x8ab94), ('associations',0x8ac17), ('use',0x8b726),
                         ('loop',0x71699), ('notify',0x716eb)]:
        raw = re.search(r'\b'+name+r'\[\]\s*(?:=)?\s*\{([^}]+)\}',install).group(1)
        expected = bytes(int(x.strip(),0) for x in raw.split(',') if x.strip())
        assert b[offset:offset+len(expected)] == expected, name
    # HDCP1's reference binding and HDCP2's null-manager consumer are independent
    # donor evidence, not values generated by the production adapter.
    assert b[0x8674b:0x86756] == bytes.fromhex('48 8b 80 40 0c 00 00 48 89 43 38')

code = r'''
#include <cassert>
#include <cstdint>
#include <cstdio>
#include <cstring>
struct IORegistryEntry {
 static IORegistryEntry *getRegistryRoot(){static IORegistryEntry r;return &r;}
 void setProperty(const char *,const void *,size_t){}
};
#define SYSLOG(...) do {} while (0)
#define FunctionCast(f,p) reinterpret_cast<decltype(&f)>(p)
struct XE {uintptr_t orgTGLHDCP2Init;static bool wrapTGLHDCP2Init(void *,void *);};
XE state{},*callbackXE=&state;
bool result=true;unsigned calls=0;
bool native(void *,void *) {++calls;return result;}
BODY
alignas(8) uint8_t hdcp[0x100],path[0x3700],fb[0x5000],ctl[0xD00],manager[0x80];
template<class T>void put(void *b,unsigned o,T v){memcpy(static_cast<uint8_t *>(b)+o,&v,sizeof(v));}
void setup(){
 memset(hdcp,0,sizeof(hdcp));memset(path,0,sizeof(path));memset(fb,0,sizeof(fb));
 memset(ctl,0,sizeof(ctl));memset(manager,0,sizeof(manager));
 result=true;calls=0;state.orgTGLHDCP2Init=reinterpret_cast<uintptr_t>(native);
 put(hdcp,0x10,ctl+0);put(hdcp,0x18,fb+0);put(hdcp,0x20,path+0);
 put(path,0x32b0,fb+0);put(fb,0x1d0,ctl+0);put(ctl,0xc40,manager+0);
 put(manager,0x50,reinterpret_cast<void *>(0x100000));put(manager,0x60,0x200000u);
}
int main(){
 setup();assert(XE::wrapTGLHDCP2Init(hdcp,path));assert(calls==1);
 assert(*reinterpret_cast<void **>(hdcp+0x38)==manager);
 assert(XE::wrapTGLHDCP2Init(hdcp,path)); // already bound is preserved.
 for(unsigned bad=0;bad<9;++bad){
  setup();void *p=path;
  if(bad==0)result=false;
  if(bad==1)p=nullptr;
  if(bad==2)put(hdcp,0x18,static_cast<void *>(nullptr));
  if(bad==3)put(hdcp,0x10,static_cast<void *>(nullptr));
  if(bad==4)put(path,0x32b0,static_cast<void *>(nullptr));
  if(bad==5)put(fb,0x1d0,static_cast<void *>(nullptr));
  if(bad==6)put(ctl,0xc40,static_cast<void *>(nullptr));
  if(bad==7)put(manager,0x50,static_cast<void *>(nullptr));
  if(bad==8)put(manager,0x60,0x650c4u);
  assert(!XE::wrapTGLHDCP2Init(hdcp,p));assert(calls==1);
  assert(!*reinterpret_cast<void **>(hdcp+0x38));
 }
 setup();put(hdcp,0x38,ctl+0);assert(!XE::wrapTGLHDCP2Init(hdcp,path));
 assert(*reinterpret_cast<void **>(hdcp+0x38)==ctl); // never overwrite another owner.
}
'''.replace('BODY',wrapper)
with tempfile.TemporaryDirectory(prefix='donor-runtime-') as d:
    p=Path(d);(p/'test.cpp').write_text(code)
    subprocess.run(['clang++','-std=c++17','-O1','-fsanitize=address,undefined',
                    str(p/'test.cpp'),'-o',str(p/'test')],check=True)
    subprocess.run([str(p/'test')],check=True)
print('PASS: borrowed HDCP2 binding, rejected associations and conflicting owner; common installation')
